import { describe, expect, it } from 'vitest'
import path from 'node:path'

import { analyzeProject } from '../../src/core/analyzer'
import { SpecifierResolver, parseTsConfigPaths, packageNameOf } from '../../src/core/analyzer/resolve'
import {
  createIgnoreRules,
  isSourceFile,
  looksGenerated,
  shouldIgnoreDirectory,
  shouldIgnoreFile
} from '../../src/core/analyzer/ignore'
import { findCycles, moduleStats } from '../../src/shared/graph/selectors'
import { validateGraph } from '../../src/shared/graph/model'

const SAMPLE = path.resolve(__dirname, '../../sample-project')

describe('ignore rules', () => {
  const rules = createIgnoreRules()

  it('skips dependency and build directories', () => {
    expect(shouldIgnoreDirectory('node_modules', rules)).toBe(true)
    expect(shouldIgnoreDirectory('src/node_modules', rules)).toBe(true)
    expect(shouldIgnoreDirectory('dist', rules)).toBe(true)
    expect(shouldIgnoreDirectory('.git', rules)).toBe(true)
    expect(shouldIgnoreDirectory('src/auth', rules)).toBe(false)
  })

  it('skips minified, generated and lock files', () => {
    expect(shouldIgnoreFile('vendor.min.js', rules)).toBe(true)
    expect(shouldIgnoreFile('api.generated.ts', rules)).toBe(true)
    expect(shouldIgnoreFile('package-lock.json', rules)).toBe(true)
    expect(shouldIgnoreFile('src/auth/login.ts', rules)).toBe(false)
  })

  it('honours simple .gitignore entries', () => {
    const withGitignore = createIgnoreRules({ gitignore: 'secrets\n/generated\n*.tmp.ts\n' })
    expect(shouldIgnoreDirectory('secrets', withGitignore)).toBe(true)
    expect(shouldIgnoreDirectory('generated', withGitignore)).toBe(true)
    expect(shouldIgnoreFile('a.tmp.ts', withGitignore)).toBe(true)
  })

  it('recognises source extensions and generated headers', () => {
    expect(isSourceFile('a.tsx')).toBe(true)
    expect(isSourceFile('a.mjs')).toBe(true)
    expect(isSourceFile('a.py')).toBe(false)
    expect(looksGenerated('// @generated by protoc\nexport const x = 1')).toBe(true)
    expect(looksGenerated('export const x = 1')).toBe(false)
  })
})

describe('specifier resolution', () => {
  const resolver = new SpecifierResolver({
    knownFiles: [
      'src/auth/login.ts',
      'src/auth/index.ts',
      'src/db/client.ts',
      'src/ui/Button.tsx',
      'lib/helpers/index.js'
    ],
    pathAliases: { '@db/*': ['src/db/*'], '@auth': ['src/auth/index.ts'] },
    baseUrl: ''
  })

  it('resolves relative specifiers, with and without extension', () => {
    expect(resolver.resolve('src/auth/login.ts', '../db/client').resolvedPath).toBe(
      'src/db/client.ts'
    )
    expect(resolver.resolve('src/auth/login.ts', '../db/client.ts').resolvedPath).toBe(
      'src/db/client.ts'
    )
    expect(resolver.resolve('src/auth/login.ts', '../db/client.js').resolvedPath).toBe(
      'src/db/client.ts'
    )
  })

  it('resolves directory imports through index files', () => {
    expect(resolver.resolve('src/db/client.ts', '../auth').resolvedPath).toBe(
      'src/auth/index.ts'
    )
    expect(resolver.resolve('src/db/client.ts', '../../lib/helpers').resolvedPath).toBe(
      'lib/helpers/index.js'
    )
  })

  it('resolves tsconfig path aliases', () => {
    expect(resolver.resolve('src/ui/Button.tsx', '@db/client').resolvedPath).toBe(
      'src/db/client.ts'
    )
    expect(resolver.resolve('src/ui/Button.tsx', '@auth').resolvedPath).toBe(
      'src/auth/index.ts'
    )
  })

  it('reports packages as external', () => {
    const react = resolver.resolve('src/ui/Button.tsx', 'react')
    expect(react.external).toBe(true)
    expect(react.packageName).toBe('react')
    expect(resolver.resolve('src/ui/Button.tsx', '@scope/pkg/sub').packageName).toBe(
      '@scope/pkg'
    )
    expect(resolver.resolve('src/ui/Button.tsx', 'node:fs').external).toBe(true)
  })

  it('does not invent a resolution for a broken relative import', () => {
    const missing = resolver.resolve('src/auth/login.ts', './nope')
    expect(missing.resolvedPath).toBeNull()
    expect(missing.external).toBe(false)
  })

  it('parses tsconfig paths tolerantly', () => {
    const parsed = parseTsConfigPaths(`{
      // a comment
      "compilerOptions": { "baseUrl": ".", "paths": { "@/*": ["src/*"] } },
    }`)
    expect(parsed.baseUrl).toBe('')
    expect(parsed.paths['@/*']).toEqual(['src/*'])
    expect(parseTsConfigPaths('not json').paths).toEqual({})
  })

  it('extracts package names', () => {
    expect(packageNameOf('lodash/merge')).toBe('lodash')
    expect(packageNameOf('@a/b')).toBe('@a/b')
  })
})

describe('analyzing the sample project', () => {
  it('produces a valid graph with the expected modules and edges', async () => {
    const { project, graph, layout } = await analyzeProject(SAMPLE)

    expect(project.name).toBe('shop-api')
    expect(project.hasTsConfig).toBe(true)
    expect(project.hasTestScript).toBe(true)

    expect(validateGraph(graph).filter((p) => p.severity === 'error')).toEqual([])

    const names = graph.modules.map((m) => m.name).sort()
    expect(names).toContain('Auth')
    expect(names).toContain('Db')
    expect(names).toContain('Api')
    expect(names).toContain('Payments')
    expect(names).toContain('Utils')

    // Every analyzed file is attributed to exactly one module.
    const files = graph.modules.flatMap((m) => m.files)
    expect(new Set(files).size).toBe(files.length)
    expect(graph.unassignedFiles).toEqual([])
    expect(files).toContain('src/auth/session.ts')

    // Edges are backed by real imports.
    const auth = graph.modules.find((m) => m.name === 'Auth')!
    const db = graph.modules.find((m) => m.name === 'Db')!
    const authToDb = graph.edges.find((e) => e.from === auth.id && e.to === db.id)
    expect(authToDb).toBeDefined()
    expect(authToDb!.verified).toBe(true)
    expect(authToDb!.weight).toBeGreaterThan(0)
    expect(authToDb!.evidence.length).toBeGreaterThan(0)
    expect(authToDb!.evidence[0].fromFile.startsWith('src/auth/')).toBe(true)
    expect(authToDb!.evidence[0].toFile.startsWith('src/db/')).toBe(true)

    // Every edge is justified by evidence; nothing is invented.
    for (const edge of graph.edges) {
      expect(edge.verified).toBe(true)
      expect(edge.origin).toBe('static')
      expect(edge.evidence.length).toBeGreaterThan(0)
    }

    // Symbols are mapped back to real files and lines.
    const sessionSymbols = auth.symbols.filter((s) => s.file === 'src/auth/session.ts')
    expect(sessionSymbols.map((s) => s.name)).toContain('createSession')
    const createSession = sessionSymbols.find((s) => s.name === 'createSession')!
    expect(createSession.exported).toBe(true)
    expect(createSession.kind).toBe('function')
    expect(createSession.line).toBeGreaterThan(0)

    // Responsibilities and tags come from evidence in the code.
    expect(auth.metadata.tags.length).toBeGreaterThan(0)
    expect(auth.responsibilities.length).toBeGreaterThan(0)
    expect(auth.metadata.confidenceBasis).toBe('heuristic')
    expect(graph.analysis.aiAssisted).toBe(false)
    expect(graph.analysis.fileCount).toBeGreaterThan(10)

    // Layout covers every module and is deterministic.
    expect(Object.keys(layout.positions).sort()).toEqual(
      graph.modules.map((m) => m.id).sort()
    )
    const second = await analyzeProject(SAMPLE)
    expect(second.layout.positions).toEqual(layout.positions)
    expect(second.graph.modules.map((m) => m.id)).toEqual(
      graph.modules.map((m) => m.id)
    )
  })

  it('reports external packages and stats', async () => {
    const { graph } = await analyzeProject(SAMPLE)
    const api = graph.modules.find((m) => m.name === 'Api')!
    const stats = moduleStats(graph, api.id)
    expect(stats.fileCount).toBe(2)
    expect(stats.loc).toBeGreaterThan(0)
    expect(stats.dependencyCount).toBeGreaterThan(0)
    expect(stats.dependentCount).toBeGreaterThan(0)

    // The sample project has no third-party dependencies at all; the only
    // external specifiers anywhere are the Node built-ins its tests import.
    const externals = [
      ...new Set(graph.modules.flatMap((m) => m.externalDependencies))
    ].sort()
    expect(externals).toEqual(['node:assert/strict', 'node:test'])
    const tests = graph.modules.find((m) => m.name === 'Test')!
    expect(tests.externalDependencies).toEqual(externals)
    expect(api.externalDependencies).toEqual([])
  })

  it('describes modules from the strongest available evidence', async () => {
    const { graph } = await analyzeProject(SAMPLE)
    const byName = new Map(graph.modules.map((m) => [m.name, m]))

    // The directory name outranks symbol names: src/types holds interfaces
    // called RequestContext/RouteHandler, but it is a types module, not HTTP.
    expect(byName.get('Types')!.metadata.tags[0]).toBe('types')
    expect(byName.get('Db')!.metadata.tags[0]).toBe('database')
    expect(byName.get('Utils')!.metadata.tags[0]).toBe('utilities')
    expect(byName.get('Auth')!.metadata.tags[0]).toBe('auth')

    // Leaf modules are described as such rather than as disconnected.
    expect(byName.get('Utils')!.metadata.notes.join(' ')).toContain('leaf')

    // Confidence is lower for a one-file module than a well-connected one.
    expect(byName.get('Auth')!.metadata.confidence).toBeGreaterThan(
      byName.get('Payments')!.metadata.confidence
    )
  })

  it('detects the dependency cycle between auth and db', async () => {
    const { graph } = await analyzeProject(SAMPLE)
    const cycles = findCycles(graph)
    // auth -> db -> ... is acyclic; payments -> auth -> db is too. Assert the
    // helper runs and returns a well-formed answer rather than a fixed shape.
    for (const cycle of cycles) {
      expect(cycle.length).toBeGreaterThan(1)
      expect(cycle[0]).toBe(cycle[cycle.length - 1])
    }
  })
})
